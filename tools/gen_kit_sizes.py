"""Regenerate src/world3d/kitSizes.ts from public/assets/models/index.json (art agent output)."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(root, 'public/assets/models/index.json'), encoding='utf-8'))
lines = ['/** Generated by tools/gen_kit_sizes.py from public/assets/models/index.json: [minX, minY, minZ, maxX, maxY, maxZ] (glTF axes, front = -Z). */',
         'export const KIT_BOUNDS: Record<string, [number, number, number, number, number, number]> = {']
for k in sorted(d):
    if k.startswith('car_') or k.startswith('wheel_'):
        continue
    mn, mx = d[k]['min'], d[k]['max']
    lines.append(f"  {k}: [{mn[0]}, {mn[1]}, {mn[2]}, {mx[0]}, {mx[1]}, {mx[2]}],")
lines.append('};')
open(os.path.join(root, 'src/world3d/kitSizes.ts'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('ok', len(lines) - 3)
